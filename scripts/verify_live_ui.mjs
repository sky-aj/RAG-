import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

// This runs real UI + API + providers against the isolated validation server.
// There is no route interception or simulated model response.
const require = createRequire(process.argv[2] ? path.join(path.resolve(process.argv[2]), 'package.json') : import.meta.url)
const { chromium } = require('playwright')
const url = process.argv[3] ?? 'http://127.0.0.1:5001'
assert.equal(new URL(url).hostname, '127.0.0.1')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'docs/live-model-validation-2026-10-12')
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1480, height: 1000 } })
page.setDefaultTimeout(30000)
const errors = []
page.on('pageerror', error => errors.push(String(error)))
const evidence = { started_at: new Date().toISOString(), simulated_api: false,
  fault_source: 'Controlled local HTTP 503; actual GLM output and RAGAS scores.' }
async function fault(mode) {
  const response = await page.request.post(url + '/__validation/fault', { data: { mode } })
  assert.equal(response.status(), 200)
}
async function ask(question, model) {
  await page.fill('.composer-input', question)
  await page.press('.composer-input', 'Enter')
  await page.waitForFunction(() => !document.querySelector('.send-btn--stop'))
  const answer = page.locator('.msg--assistant').last()
  const text = await answer.innerText()
  assert.ok(text.includes(`本次模型：${model}`), text)
  assert.ok(!text.includes('回答流意外中断'), text)
  assert.ok((await answer.locator('.msg-text').innerText()).includes('600'))
  return { answer, summary: { actual_model: model, visible_text: text } }
}
try {
  await fault('off')
  await page.goto(url, { waitUntil: 'networkidle' })
  await page.locator('.status-pill.is-online').waitFor()
  await page.locator('.engine').getByText('sub-coco · deepseek-v4-flash', { exact: true }).waitFor()
  const primary = await ask('接口默认限流额度是多少？超出后会返回什么？', 'deepseek-v4-flash')
  evidence.primary_chat = primary.summary
  await page.screenshot({ path: path.join(out, '01-primary-chat.png') })
  console.log('PASS: actual DeepSeek answer and citations in browser.')

  await fault('503')
  const fallback = await ask('默认限流额度是多少？请简短说明超限的处理。', 'glm-4-flash')
  assert.ok((await fallback.answer.innerText()).includes('已切换至 glm-4-flash'))
  assert.ok((await fallback.answer.innerText()).includes('本次模型：glm-4-flash'))
  evidence.fallback_chat = fallback.summary
  await page.reload({ waitUntil: 'networkidle' })
  assert.ok((await page.locator('.msg--assistant').last().innerText()).includes('已切换至 glm-4-flash'))
  await page.screenshot({ path: path.join(out, '02-real-fallback-restored.png') })
  console.log('PASS: actual GLM fallback, visible notice, refresh persistence.')

  await page.locator('.nav-item').getByText('知识库', { exact: true }).click()
  await page.getByRole('button', { name: '评测', exact: true }).click()
  await page.locator('.eval-case').first().waitFor()
  assert.equal(await page.locator('.eval-metric').count(), 4)
  assert.ok((await page.locator('.eval-metric strong').allTextContents()).every(value => value !== '—'))
  await page.screenshot({ path: path.join(out, '03-primary-ragas.png') })

  await page.locator('.num-input').fill('1')
  const generated = page.waitForResponse(response => response.url().endsWith('/api/eval/dataset') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '生成评测集', exact: true }).click()
  const generation = await (await generated).json()
  assert.equal(generation.count, 1)
  assert.equal(generation.cases[0].generation_model, 'glm-4-flash')
  assert.ok(generation.notes.some(note => note.includes('glm-4-flash')))
  evidence.fallback_dataset = generation
  await page.getByText('生成 1 道题', { exact: false }).waitFor()
  assert.ok((await page.locator('.panel-note').allTextContents()).some(note => note.includes('glm-4-flash')))
  await page.screenshot({ path: path.join(out, '04-real-fallback-dataset.png') })
  console.log('PASS: dataset generated by actual GLM; fallback notice visible.')

  const scored = page.waitForResponse(response => response.url().endsWith('/api/eval/run') && response.request().method() === 'POST', { timeout: 900000 })
  await page.getByRole('button', { name: '跑一轮评测', exact: true }).click()
  console.log('Running actual RAGAS through UI with primary HTTP 503 and real GLM generation/judge...')
  const report = await (await scored).json()
  evidence.fallback_report = report
  const variant = report.variants[0]
  assert.equal(variant.retrieval.failed_answers, 0)
  assert.equal(variant.retrieval.empty_answers, 0)
  assert.ok(['faithfulness', 'answer_relevancy', 'context_precision', 'context_recall'].every(key => variant.scores[key] != null))
  assert.equal(variant.per_case[0].actual_model, 'glm-4-flash')
  assert.ok(report.notes.some(note => note.includes('部分判分使用了 GLM')))
  await page.getByText('跑完 1 条样本', { exact: false }).waitFor()
  await page.locator('.eval-case').first().click()
  await page.locator('.eval-case-body').waitFor()
  assert.ok((await page.locator('.eval-case-body').innerText()).includes('glm-4-flash'))
  assert.ok((await page.locator('.panel-note').allTextContents()).some(note => note.includes('部分判分使用了 GLM')))
  await page.screenshot({ path: path.join(out, '05-real-fallback-ragas.png') })
  await page.reload({ waitUntil: 'networkidle' })
  await page.locator('.nav-item').getByText('知识库', { exact: true }).click()
  await page.getByRole('button', { name: '评测', exact: true }).click()
  await page.locator('.eval-case').first().waitFor()
  assert.ok((await page.locator('.panel-note').allTextContents()).some(note => note.includes('部分判分使用了 GLM')))
  assert.ok(await page.locator('.eval-history tbody tr').count() >= 2)
  console.log('PASS: four actual RAGAS scores, generation/judge notices, saved report after reload.')
  assert.deepEqual(errors, [])
  evidence.passed = true
} catch (error) {
  evidence.passed = false
  evidence.error = String(error)
  await page.screenshot({ path: path.join(out, 'failure.png') }).catch(() => {})
  throw error
} finally {
  await fault('off').catch(() => {})
  evidence.finished_at = new Date().toISOString()
  evidence.page_errors = errors
  await fs.writeFile(path.join(out, 'browser-live.json'), JSON.stringify(evidence, null, 2), 'utf8')
  await browser.close()
}
